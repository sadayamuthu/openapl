# sdk/src/openapl/evidence.py
"""OSCAL 1.2.3 assessment-results built from the decision log.

Patterns copied from opengpl-by-design/opengpl/sdk/src/opengpl/audit/oscal.py.
The document says decisions were recorded. It makes no claim that any control
is met; the `satisfied` state is the status value OSCAL requires on a finding
target and is paired with a description that only counts recorded decisions.
"""
import uuid
from datetime import datetime, timezone

from openapl.controls import LOG_CONTROLS

OSCAL_VERSION = "1.2.3"
NS = "https://openapl.org/ns/oscal"
UUID_NS = uuid.uuid5(uuid.NAMESPACE_URL, NS)
_VALUES = ("ALLOW", "DENY", "REQUIRE_APPROVAL")


def _uuid(key: str) -> str:
    return str(uuid.uuid5(UUID_NS, key))


def _prop(name: str, value: str) -> dict:
    return {"name": name, "ns": NS, "value": value}


def _stamp(epoch: int) -> str:
    return datetime.fromtimestamp(epoch, tz=timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _token(control: str) -> str:
    # OSCAL tokens are NCNames, which exclude ':'.
    return control.replace(":", "-")


def assessment_results(records: list[dict], *, title: str, since: int, until: int,
                       now: str) -> dict:
    kept: list[dict] = []
    seen: set[str] = set()
    for r in records:  # first occurrence of a decision id wins
        if r["decision_id"] not in seen:
            seen.add(r["decision_id"])
            kept.append(r)

    observations = []
    for r in kept:
        did = r["decision_id"]
        policies = ",".join(r.get("policies") or [])
        observations.append({
            "uuid": _uuid(f"obs:{did}"),
            "title": f"{r['decision']}: {r['action']} on {r['resource']}",
            "description": f"Decision {r['decision']} recorded in the decision log.",
            "methods": ["TEST"],
            "collected": _stamp(r["timestamp"]),
            "props": [
                _prop("decision", str(r["decision"])),
                _prop("chain", ",".join(r.get("chain") or [])),
                _prop("action", str(r["action"])),
                _prop("resource", str(r["resource"])),
                _prop("policies", policies),
            ],
            "relevant-evidence": [{
                "description": (f"Decision log line with decision_id {did}, "
                                f"timestamp {r['timestamp']}.")
            }],
        })
    obs_uuid = {r["decision_id"]: o["uuid"] for r, o in zip(kept, observations)}

    controls = sorted({c for r in kept for c in (r.get("controls") or [])} | set(LOG_CONTROLS))
    ar_key = f"{title}:{since}:{until}:" + ",".join(sorted(obs_uuid))
    findings = []
    for control in controls:
        cited = [r for r in kept if control in LOG_CONTROLS or control in (r.get("controls") or [])]
        counts = ", ".join(f"{sum(1 for r in cited if r['decision'] == v)} {v}" for v in _VALUES)
        findings.append({
            "uuid": _uuid(f"finding:{ar_key}:{control}"),
            "title": f"Decisions recorded for {control}",
            "description": (f"{len(cited)} decisions recorded citing {control}: {counts}. "
                            "This lists recorded decisions; it is not an assessment."),
            "props": [_prop("control", control)],
            "target": {
                "type": "objective-id",
                "target-id": _token(control),
                "status": {"state": "satisfied"},
            },
            "related-observations": [{"observation-uuid": obs_uuid[r["decision_id"]]}
                                     for r in cited],
        })

    res_uuid = _uuid(f"res:{ar_key}")
    result = {
        "uuid": _uuid(f"result:{ar_key}"),
        "title": "OpenAPL decision records",
        "description": ("Decisions recorded in the OpenAPL decision log, listed as observations. "
                        "This is evidence for an assessor, not an assessment."),
        "start": _stamp(since),
        "end": _stamp(until),
        "reviewed-controls": {"control-selections": [{
            "include-controls": [{"control-id": _token(c)} for c in controls]
        }]},
        "observations": observations,
        "findings": findings,
    }
    return {"assessment-results": {
        "uuid": _uuid(f"ar:{ar_key}"),
        "metadata": {
            "title": title,
            "last-modified": now,
            "version": "0.1",
            "oscal-version": OSCAL_VERSION,
        },
        "import-ap": {"href": f"#{res_uuid}"},
        "results": [result],
        "back-matter": {"resources": [{
            "uuid": res_uuid,
            "title": "No assessment plan",
            "description": ("Generated by openapl from decision log records. No assessment plan "
                            "exists; these are recorded decisions, not an assessment."),
        }]},
    }}
